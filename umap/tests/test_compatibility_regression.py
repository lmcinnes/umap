"""Seeded ``compatibility_layout=True`` fits must reproduce the final 0.5.x line.

Fixtures are generated by ``data/make_compat_fixtures.py`` from the 0.5.x
``master`` commit merged into 0.6 (0.5.12 plus later bug fixes). numba code generation (and libm) can differ across
platforms and numba versions, so bit-exact comparison is only asserted when
both match the fixture's provenance.
"""

import os
import platform
import warnings

import numba
import numpy as np
import pytest

import umap
from umap.tests import _compat_cases

# CI regenerates the fixtures in its own environment (see
# data/make_compat_fixtures.py) so the exact comparison always runs there.
FIXTURE_PATH = os.environ.get(
    "UMAP_COMPAT_FIXTURES",
    os.path.join(os.path.dirname(__file__), "data", _compat_cases.FIXTURE_FILE),
)


@pytest.fixture(scope="module")
def fixtures():
    with np.load(FIXTURE_PATH) as stored:
        return {key: stored[key] for key in stored.files}


def _matching_environment(fixtures):
    return (
        str(fixtures["platform"]) == f"{platform.system()}-{platform.machine()}"
        and str(fixtures["numba_version"]) == numba.__version__
    )


@pytest.mark.parametrize("case_name", sorted(_compat_cases.build_cases()))
def test_compatibility_layout_reproduces_0_5(fixtures, case_name):
    fit_data, target, transform_data, kwargs = _compat_cases.build_cases()[case_name]
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        results = _compat_cases.run_case(
            umap,
            fit_data,
            target,
            transform_data,
            kwargs,
            extra_kwargs=dict(compatibility_layout=True),
        )

    for key, value in results.items():
        expected = fixtures[f"{case_name}/{key}"]
        assert value.shape == expected.shape
        assert np.all(np.isfinite(value))

    if not _matching_environment(fixtures):
        pytest.skip(
            "bit-exact comparison requires fixtures generated on "
            f"{fixtures['platform']} with numba {fixtures['numba_version']}"
        )
    for key, value in results.items():
        np.testing.assert_array_equal(
            value, fixtures[f"{case_name}/{key}"], err_msg=f"{case_name}/{key}"
        )


def test_aligned_compatibility_layout_reproduces_0_5(fixtures):
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        results = _compat_cases.run_aligned_case(umap, dict(compatibility_layout=True))
    for key, value in results.items():
        assert value.shape == fixtures[f"aligned/{key}"].shape
    if not _matching_environment(fixtures):
        pytest.skip("bit-exact comparison requires matching platform and numba")
    for key, value in results.items():
        np.testing.assert_array_equal(
            value, fixtures[f"aligned/{key}"], err_msg=f"aligned/{key}"
        )
